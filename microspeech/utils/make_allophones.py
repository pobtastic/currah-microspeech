"""Pack SP0256-AL2 PCM arrays into sources/allophones.js.

Reads a wav2byt-style allophones.c (from ExtremeElectronics/RC2040, itself
taken from the CPCWiki chip recordings) and writes a compact base64 blob
using the time-corrected lengths.
"""

import base64
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "sources" / "allophones.js"

NAMES = [
    "PA1", "PA2", "PA3", "PA4", "PA5",
    "OY", "AY", "EH", "KK3", "PP", "JH", "NN1", "IH", "TT2", "RR1", "AX",
    "MM", "TT1", "DH1", "IY", "EY", "DD1", "UW1", "AO", "AA", "YY2", "AE",
    "HH1", "BB1", "TH", "UH", "UW2", "AW", "DD2", "GG3", "VV", "GG1", "SH",
    "ZH", "RR2", "FF", "KK2", "KK1", "ZZ", "NG", "LL", "WW", "XR", "WH",
    "YY1", "CH", "ER1", "ER2", "OW", "DH2", "SS", "NN2", "HH2", "OR", "AR",
    "YR", "GG2", "EL", "BB2",
]


def parse_c(text):
    arrays = {}
    for match in re.finditer(
        r"const uint8_t (a\d+[a-z0-9]+)\[] = \{(.*?)\};",
        text,
        re.S,
    ):
        name, body = match.group(1), match.group(2)
        values = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]+)", body)]
        arrays[name] = values

    sizes = [
        int(x)
        for x in re.search(
            r"const int allophonesize\[64]=\{(.*?)\};", text, re.S
        ).group(1).split(",")
        if x.strip()
    ]
    corrected = [
        int(x)
        for x in re.search(
            r"const int allophonesizeCorrected\[64]=\{(.*?)\};", text, re.S
        ).group(1).split(",")
        if x.strip()
    ]
    index = re.search(
        r"const uint8_t \*allophoneindex\[64]=\{(.*?)\};", text, re.S
    ).group(1)
    names = [n.strip() for n in index.split(",") if n.strip()]
    if len(names) != 64 or len(sizes) != 64 or len(corrected) != 64:
        raise SystemExit("expected 64 allophones")
    pcm = []
    for name, size, cut in zip(names, sizes, corrected):
        data = arrays[name]
        if len(data) < size:
            raise SystemExit(f"{name}: got {len(data)} bytes, expected {size}")
        pcm.append(bytes(data[:cut]))
    return pcm


def main():
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("/tmp/allophones.c")
    pcm = parse_c(src.read_text())
    blob = b"".join(pcm)
    lengths = [len(p) for p in pcm]
    b64 = base64.b64encode(blob).decode("ascii")
    names = ",".join(f'"{n}"' for n in NAMES)
    length_s = ",".join(str(n) for n in lengths)
    OUT.write_text(
        "/* SP0256-AL2 8-bit PCM at 11025 Hz.\n"
        " * Recordings: https://www.cpcwiki.eu/index.php/SP0256_Allophones\n"
        " * Packed from ExtremeElectronics/RC2040 allophones.c\n"
        " * (time-corrected lengths). Regenerated by\n"
        " * utils/make_allophones.py — do not hand-edit.\n"
        " */\n"
        "window.USPEECH_PCM={\n"
        "rate:11025,\n"
        f"names:[{names}],\n"
        f"lengths:[{length_s}],\n"
        f'data:"{b64}"\n'
        "};\n"
    )
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(blob)} samples)")


if __name__ == "__main__":
    main()
